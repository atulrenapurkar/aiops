    private void store(SourceType source, String id, String title, String content, String metadata) {
        try {
            vectorStoreService.store(source, id, title, content.strip(), metadata);
            log.info("  Seeded [{}] {}", source, title);
        } catch (Exception e) {
            log.error("  Failed to seed [{}] {}: {}", source, title, e.getMessage());
        }
    }
